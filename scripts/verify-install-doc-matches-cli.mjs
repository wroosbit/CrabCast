const cliSource = read(CLI);
const cliAst = ts.createSourceFile(CLI, cliSource, ts.ScriptTarget.ES2022, true);

/** The initializer of a top-level `export const <name> = …`, unwrapping `as const`. */
function topLevelConst(name) {
  for (const st of cliAst.statements) {
    if (!ts.isVariableStatement(st)) continue;
    for (const d of st.declarationList.declarations) {
      if (!ts.isIdentifier(d.name) || d.name.text !== name) continue;
      let init = d.initializer;
      if (init && ts.isAsExpression(init)) init = init.expression;
      return init ?? null;
    }
  }
  return null;
}

/** `EXIT` as `{ MEMBER: number }`, or null if it is not the shape we expect. */
function readExitTable() {
  const init = topLevelConst('EXIT');
  if (!init || !ts.isObjectLiteralExpression(init)) return null;
  const out = {};
  for (const p of init.properties) {
    if (!ts.isPropertyAssignment(p) || !ts.isIdentifier(p.name)) return null;
    if (!ts.isNumericLiteral(p.initializer)) return null;
    out[p.name.text] = Number(p.initializer.text);
  }
  return out;
}

/** One command table as `[{ name, spawnsDaemon }]`, or null. */
function readCommandTable(tableName) {
  const init = topLevelConst(tableName);
  if (!init || !ts.isArrayLiteralExpression(init)) return null;
  const rows = [];
  for (const el of init.elements) {
    if (!ts.isObjectLiteralExpression(el)) return null;
    const row = {};
    for (const p of el.properties) {
      if (!ts.isPropertyAssignment(p) || !ts.isIdentifier(p.name)) continue;
      if (p.name.text === 'name' && ts.isStringLiteral(p.initializer)) {
        row.name = p.initializer.text;
      }
      if (p.name.text === 'spawnsDaemon') {
        if (p.initializer.kind === ts.SyntaxKind.TrueKeyword) row.spawnsDaemon = true;
        else if (p.initializer.kind === ts.SyntaxKind.FalseKeyword) row.spawnsDaemon = false;
        else return null;
      }
    }
    if (!row.name) return null;
    rows.push(row);
  }
  return rows;
}

