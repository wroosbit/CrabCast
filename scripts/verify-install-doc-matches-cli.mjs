// THREE SHAPES, AND THE THIRD WAS ADDED BECAUSE THE FIRST TWO MISSED ONE.
// `EXIT=n` catches the driven console blocks and `exits n` / ``fails `n` ``
// catches the prose that names a verb — but §4.1's *"Its exit status is the
// daemon's own — `0` for a clean shutdown"* is a claim about an exit code that
// uses neither wording, and the sweep read straight past it. That is this
// file's own *an empty result is a claim about your search*: the register said
// every claim was accounted for, over a list one claim short. So shape 3 takes
// a lone quoted integer on any line that mentions exiting at all, which is what
// reaches it — and keeps a version number in a table (`8`, at §6) out, because
// that line says nothing about an exit.
//
// WHAT STILL ESCAPES, named rather than left for somebody to discover: a claim
// with NO DIGIT IN IT. §4.1's own next clause is *"non-zero for a refusal to
// boot"*, which is a real statement about exit codes and matches nothing here.
// Widening to catch it would mean matching prose, and there is no register
// entry shape that reconciles "non-zero" against a table of numbers.
const SWEEP = [
  /\b(?:[A-Z][A-Z0-9_]*_)?EXIT\s*=\s*(\d+)/g,
  /\bexits?\s+(?:\*\*|`)?(\d+)(?:\*\*|`)?/g,
  /\bfails\s+`(\d+)`/g,
  /(?:`(\d+)`|\*\*(\d+)\*\*)/g
];
const MENTIONS_EXITING = /\bexit|\bfails\b/i;

const hits = [];
setupLines.forEach((line, i) => {
  // One claim per (line, value): a line matched by two shapes — `exits **4**`
  // is both shape 2 and shape 4 — is one claim written once, not two.
  const seen = new Set();
  for (const [shape, re] of SWEEP.entries()) {
    if (shape === 3 && !MENTIONS_EXITING.test(line)) continue;
    re.lastIndex = 0;
    let m;
    while ((m = re.exec(line))) {
      const value = Number(m.slice(1).find((g) => g !== undefined));
      if (seen.has(value)) continue;
      seen.add(value);
      hits.push({ line: i + 1, value, text: line.trim() });
    }
  }
});
hits.sort((a, b) => a.line - b.line);

console.log(`  the sweep found ${hits.length} exit-code claim(s) in ${SETUP}\n`);

// A floor for the sweep itself. A regex that stopped matching would report
// "every claim accounted for" over an empty list.
check(hits.length >= 12, `the sweep found at least 12 claims in ${SETUP}`, `${hits.length}`);

// Resolve each entry to its hit, in document order, before judging any of them:
// a claim's identity is its anchor, and which hit that is has to be settled
// before "the register accounts for this one" can mean anything.
const claimed = new Map(); // hit -> entry
const stale = [];
for (const entry of EXIT_CLAIMS) {
  let hit;
  if (entry.after !== undefined) {
    // `after` names a line that carries no digit of its own; the claim is the
    // first one at or below it. The line must be unique, or the entry is
    // pointing at a place in the page rather than at a place.
    const occurrences = setupLines.filter((l) => l.includes(entry.after)).length;
    if (occurrences !== 1) {
      check(false, `the register entry after ${JSON.stringify(entry.after)} names one line`, `found ${occurrences} — broken register, not a finding`);
      continue;
    }
    const from = setupLines.findIndex((l) => l.includes(entry.after)) + 1;
    hit = hits.find((h) => h.line >= from);
  } else {
    hit = hits.filter((h) => h.text.includes(entry.anchor))[(entry.nth ?? 1) - 1];
  }
  if (!hit) {
    stale.push(entry);
    continue;
  }
  if (claimed.has(hit)) {
    check(false, `the register entry ${JSON.stringify(entry.anchor ?? entry.after)} claims a hit of its own`, `${SETUP}:${hit.line} is already claimed by ${JSON.stringify(claimed.get(hit).anchor ?? claimed.get(hit).after)} — two entries, one claim; broken register, not a finding`);
    continue;
  }
  claimed.set(hit, entry);
}

for (const hit of hits) {
  const entry = claimed.get(hit);
  if (!entry) {
    check(false, `${SETUP}:${hit.line} quotes exit \`${hit.value}\` and the register accounts for it`, `no EXIT_CLAIMS entry anchors on this line — add a \`member\` reconciling it, or a \`why\` saying it is not a CrabCast client exit code: ${JSON.stringify(hit.text.slice(0, 72))}`);
    continue;
  }
  if (entry.member === null) {
    check(true, `${SETUP}:${hit.line} exit \`${hit.value}\` is EXCLUDED`, entry.why);
    continue;
  }
  const have = EXIT[entry.member];
  check(
    have === hit.value,
    `${SETUP}:${hit.line} quotes EXIT.${entry.member} — ${entry.what}`,
    have === hit.value ? `both ${hit.value}` : `page says ${hit.value}, src/cli.ts says EXIT.${entry.member} = ${have === undefined ? '(no such member)' : have}`
  );
}

// The register's other direction: an entry whose claim has been edited out of
// the page is a rule guarding nothing, and it degrades toward looking covered.
check(
  stale.length === 0,
  'every register entry still matches a claim on the page',
  stale.length
    ? `no claim found for ${stale.map((s) => JSON.stringify(s.anchor ?? s.after) + (s.nth ? ` (#${s.nth})` : '')).join(', ')} — the page moved; re-anchor or remove the entry`
    : `${EXIT_CLAIMS.length} entries, all live`
);

// ===========================================================================
console.log('\n=== 5. README.md\'s exit-code contract, by set ===\n');
//
// THE ONE PLACE ANY DOCUMENT CLAIMS THE WHOLE SET. "part of the contract",
// followed by an enumeration — so a code the CLI has and the bullet does not is
// a promise the page cannot keep. That is the failure that really happened
// (KAN-528 added `5`), and the by-set comparison is the whole of what would
// have caught it. `SETUP.md` makes no such claim anywhere, which is why §4
// checks its values one at a time and builds no set machinery for a set that is
// not asserted.

const CONTRACT_ANCHOR = '**Exit codes** are part of the contract:';
const contractCount = readmeText.split(CONTRACT_ANCHOR).length - 1;
if (contractCount !== 1) {
  check(false, `${README}: the exit-code contract bullet is found exactly once`, `found ${contractCount}× — broken entry, not a finding`);
} else {
  const at = readmeText.split('\n').findIndex((l) => l.includes(CONTRACT_ANCHOR));
  const bullet = readmeText.split('\n')[at];
  // THE ENUMERATION, NOT THE BULLET. The items are ` · `-separated and each
  // one OPENS with its code, so a code is what a segment starts with — never
  // any number that appears in the sentence. Reading the whole bullet instead
  // lets the prose explaining a code contribute it a second time, and the
  // set comparison then reports a difference that is a fact about the writing.
  const published = bullet
    .slice(bullet.indexOf(CONTRACT_ANCHOR) + CONTRACT_ANCHOR.length)
    .split(' · ')
    .map((seg) => /^\s*`(\d+)`/.exec(seg))
    .filter(Boolean)
    .map((m) => Number(m[1]));
  const actual = Object.values(EXIT);

  check(published.length > 0, `${README}:${at + 1} enumerates the codes it calls the contract`, `${published.length} found`);
  check(
    sameSet(published, actual),
    `${README}:${at + 1} publishes exactly the set src/cli.ts defines`,
    sameSet(published, actual)
      ? asSet(actual)
      : `page publishes [${asSet(published)}], EXIT is [${asSet(actual)}]; missing from the page: [${asSet(actual.filter((v) => !published.includes(v)))}], on the page but not in EXIT: [${asSet(published.filter((v) => !actual.includes(v)))}]`
  );

  // Each published code must also be spelled with the meaning its member
  // carries. A set that matches while `3` and `4` have swapped descriptions is
  // a page that is wrong in the way a reader would act on.
  const MEANINGS = [
    { member: 'OK', phrase: 'success' },
    { member: 'REFUSED', phrase: 'the daemon answered `success: false`' },
    { member: 'USAGE', phrase: 'usage error' },
    { member: 'TRANSPORT', phrase: 'could not reach or spawn the daemon' },
    { member: 'CONFIG', phrase: 'a config that was named would not load' },
    { member: 'OVERSIZE', phrase: 'the answer would not fit the socket' }
  ];
  for (const meaning of MEANINGS) {
    if (!(meaning.member in EXIT)) {
      check(false, `${README}: EXIT.${meaning.member} still exists`, 'the register names a member src/cli.ts no longer has — broken entry, not a finding');
      continue;
    }
    const want = `\`${EXIT[meaning.member]}\` ${meaning.phrase}`;
    check(bullet.includes(want), `${README}:${at + 1} spells EXIT.${meaning.member} as ${JSON.stringify(want)}`, bullet.includes(want) ? '' : 'not found on the bullet in that wording');
  }
}

